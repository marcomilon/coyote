export const STRINGS = { es, pt };
export type Strings = typeof es;

/** `base` with `override` laid over it: objects merge key by key, anything else (strings, arrays) is replaced. */
function overlay<T>(base: T, override: DeepPartial<T> | undefined): T {
  if (override === undefined) return base;
  if (typeof base !== 'object' || base === null || Array.isArray(base)) return override as T;
  const out: Record<string, unknown> = { ...(base as Record<string, unknown>) };
  for (const [key, value] of Object.entries(override as Record<string, unknown>)) {
    out[key] = overlay((base as Record<string, unknown>)[key], value as never);
  }
  return out as T;
}

